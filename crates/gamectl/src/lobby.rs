//! The lobby's Probation match, hosted here as the lobby has `gamectl host`
//! host it, for `gamectl verify --preset probation` (S3's `nite3`).
//!
//! # Why a second view
//!
//! The reference seat view ([`crate::seat`]) is the verifier's fixture: a core
//! `b_01`, a Mine beacon `b_02`, one known enemy beacon. A Probation playbook
//! is written for the newcomer's first match, where the seat's core is `b_00`
//! and the beacons, the vents and the spheres are the match's, so against the
//! reference view its `b_00` is `E0401` and its placements may be `E0403`:
//! `gamectl verify` could not check one. With `--preset probation` it checks
//! the file against **the match the lobby opens**, the way the editor does.
//!
//! # The view comes from where the lobby's does
//!
//! Not a second hand-written fixture. The match is the one the lobby's config
//! line describes ([`PROBATION_LINE`], the line `godot/scripts/host_link.gd`'s
//! `config_line` writes for its own defaults, less the match id, which reaches
//! nothing hashed), read by the gateway's own reader
//! ([`Config::parse`]), generated by the gateway's own
//! [`Host::open_from`] from the same rules text `gamectl host` reads, and put
//! behind a [`Surface`] with the preset and the human seat
//! ([`Surface::with_preset`]) in its opening Lull, as `serve`'s own
//! `open_surface` does. The playbook then goes through `verify_plan` on the
//! human seat's own token: the gateway verifies it against that seat's frozen
//! snapshot and its own seat view, and this module reads the report off the
//! answer. Nothing here builds a snapshot or a scope.
//!
//! `tests/verify.rs` holds [`PROBATION_LINE`]'s fields to the lobby's own
//! constants in `host_link.gd` and its seed to the sim's pin
//! (`crates/sim/tests/probation_seed.rs`'s `PROBATION_SEED`), so the line
//! cannot drift from the lobby's in silence.
//!
//! No template library is opened: verifying reads none, and the world a
//! config line generates does not depend on it.

use std::path::Path;

use pharmakos_gateway::Code;
use pharmakos_gateway::fog::{Blind, FogPolicy};
use pharmakos_gateway::host::{Host, Settings};
use pharmakos_gateway::scopes::{Scope, ScopeSet};
use pharmakos_gateway::serve::Config;
use pharmakos_gateway::surface::Surface;
use pharmakos_gateway::token::Subject;
use pharmakos_proto::gp::api::v1::VerifyReport;
use pharmakos_proto::gp::api::v1::verify_plan::Depth;
use pharmakos_proto::json::Json;
use pharmakos_sim::math::quantity::Tick;
use pharmakos_sim::tables::SeatId;

use crate::exit::Failure;
use crate::{rules, strings};

/// The config line the lobby writes for a Probation match, with this
/// module's own match id: the id, the seed, the seats, the human seat, the
/// segment ladder (`-`, the rules table's own), the round limit and the
/// preset, tab separated (`crate::host`'s protocol, `serve::Config`).
pub const PROBATION_LINE: &str = "m-verify-probation\t0x0000000000000014\t2\t0\t-\t3\tprobation";

/// The lobby's Probation match, as the gateway reads its config line.
///
/// # Errors
///
/// [`crate::exit::Exit::Internal`] when the gateway refuses the line, which
/// would be this build's gateway and this build's copy of the lobby's line
/// disagreeing.
pub fn probation() -> Result<Config, Failure> {
    Config::parse(PROBATION_LINE)
        .map_err(|error| Failure::internal(strings::lobby_line_refused(&error.to_string())))
}

/// The seat whose view a preset verifies against: the lobby's human seat.
///
/// # Errors
///
/// [`crate::exit::Exit::Internal`] for a line with no human seat, which the
/// lobby's never is.
pub fn seat_of(config: &Config) -> Result<u8, Failure> {
    config
        .human_seat
        .ok_or_else(|| Failure::internal(strings::lobby_line_refused("it names no human seat")))
}

/// Verify `playbook_jsonc` against the human seat's frozen snapshot in the
/// opening Lull of the lobby's Probation match, at `depth`.
///
/// `None` is a file past the size cap in bytes, which [`crate::verify`]
/// refused to read further: the gateway is handed a text one character past
/// [`pharmakos_verifier::MAX_PLAYBOOK_CHARS`], which it refuses before
/// verifying, counting no further than one character past the cap, exactly as
/// it refuses the file's own text.
///
/// # Errors
///
/// [`crate::exit::Exit::Input`] when the rules table cannot be read,
/// [`crate::exit::Exit::Failed`] when the gateway refuses the text before
/// verifying it, and [`crate::exit::Exit::Internal`] when the match will not
/// open or the gateway's answer is not a report.
pub fn verify(
    root: &Path,
    playbook_jsonc: Option<&str>,
    depth: Depth,
) -> Result<VerifyReport, Failure> {
    let config = probation()?;
    let seat = seat_of(&config)?;
    let mut surface = open(root, &config)?;
    let (token, _) = surface
        .tokens()
        .mint(
            Subject::Seat(SeatId::new(seat)),
            &config.match_id,
            ScopeSet::of(&[Scope::Observe, Scope::Plan]),
            Tick::ZERO,
        )
        .map_err(gateway)?;
    let past_the_cap: String;
    let text = if let Some(text) = playbook_jsonc {
        text
    } else {
        past_the_cap = " ".repeat(
            pharmakos_verifier::MAX_PLAYBOOK_CHARS
                .checked_add(1)
                .ok_or_else(|| Failure::internal("the size cap is the largest usize"))?,
        );
        past_the_cap.as_str()
    };
    let params = pharmakos_proto::json::write(&Json::Object(vec![
        (
            String::from("playbook_jsonc"),
            Json::String(text.to_owned()),
        ),
        (
            String::from("depth"),
            Json::String(String::from(match depth {
                Depth::Quick => "quick",
                Depth::Unspecified | Depth::Full => "full",
            })),
        ),
    ]));
    let request = pharmakos_gateway::rpc::parse(&format!(
        r#"{{"jsonrpc":"2.0","id":1,"method":"verify_plan","params":{params}}}"#
    ))
    .map_err(|error| {
        Failure::internal(strings::lobby_answer_unread(&format!(
            "the gateway would not parse this command's own request: {} ({})",
            error.title(),
            error.number()
        )))
    })?;
    let answer = surface.call(Some(&token), &request, &Blind);
    report_of(&answer)
}

/// Open the lobby's match in its opening Lull, as `serve` opens one.
fn open(root: &Path, config: &Config) -> Result<Surface, Failure> {
    let path = root.join(rules::RULES_PATH);
    let rules_json = std::fs::read_to_string(&path).map_err(|error| {
        Failure::input(strings::unreadable(
            "rules table",
            &crate::display(&path),
            &error.to_string(),
        ))
    })?;
    let host = Host::open_from(
        &rules_json,
        config.seed,
        config.seats,
        &Settings {
            segment_lengths_ms: config.segment_lengths_ms.clone(),
            round_limit: config.round_limit,
        },
        None,
    )
    .map_err(gateway)?;
    let seats = (0..config.seats)
        .map(|raw| {
            u8::try_from(raw)
                .map(SeatId::new)
                .map_err(|_| Failure::internal(strings::lobby_line_refused("a seat past a u8")))
        })
        .collect::<Result<Vec<SeatId>, Failure>>()?;
    let rules = host.rules().clone();
    let mut surface = Surface::new(
        &config.match_id,
        config.seed,
        rules,
        // Fogged, as every match the lobby opens is (spec section 12).
        FogPolicy::fogged(),
        &seats,
    )
    .map_err(gateway)?
    .with_preset(config.preset, config.human_seat.map(SeatId::new));
    surface.attach(host).map_err(gateway)?;
    surface.open_lull().map_err(gateway)?;
    Ok(surface)
}

/// The report in a `verify_plan` answer, translated from the wire's spelling
/// (lower-case enum values, decisions-log item 80) back to canonical
/// `gp.api.v1.VerifyReport` JSON and decoded.
///
/// # Errors
///
/// [`crate::exit::Exit::Internal`] for a refusal, an answer with no report,
/// an enum value the schema does not name, or a report the decoder refuses:
/// each is this build's gateway and this command disagreeing.
pub fn report_of(answer: &Json) -> Result<VerifyReport, Failure> {
    if let Some(error) = answer.get("error") {
        let said = match error.get("message") {
            Some(Json::String(text)) => text.clone(),
            // No message is the wire's shape having moved: the whole error,
            // named, in a failure that is already this build's fault.
            _ => pharmakos_proto::json::write(error).trim_end().to_owned(),
        };
        // `INVALID_ARGUMENT` is the gateway refusing the text itself before
        // it verifies anything (a playbook past the size cap is one): the
        // answer the lobby's match would give, so the answer is no. Anything
        // else is this build's gateway and this command disagreeing.
        let invalid = error
            .get("data")
            .and_then(|data| data.get("code"))
            .is_some_and(|code| {
                *code == Json::String(String::from(Code::InvalidArgument.as_str_name()))
            });
        return Err(if invalid {
            Failure::failed(strings::lobby_text_refused(&said))
        } else {
            Failure::internal(strings::lobby_answer_unread(&said))
        });
    }
    let report = answer
        .get("result")
        .and_then(|result| result.get("report"))
        .ok_or_else(|| Failure::internal(strings::lobby_answer_unread("it holds no report")))?;
    let canonical = canonical_report(report)?;
    pharmakos_proto::json::decode_json::<VerifyReport>(&canonical).map_err(|error| {
        Failure::internal(strings::lobby_answer_unread(&format!(
            "its report does not decode: {error}"
        )))
    })
}

/// The enum-valued fields of a report on the wire, by where they sit: the
/// report's `depth`, each diagnostic's `severity` and each suggestion's
/// `applicability`.
const DEPTH: &str = "gp.api.v1.VerifyPlan.Depth";
const SEVERITY: &str = "gp.api.v1.Diagnostic.Severity";
const APPLICABILITY: &str = "gp.api.v1.PatchSuggestion.Applicability";

fn canonical_report(report: &Json) -> Result<Json, Failure> {
    let Json::Object(members) = report else {
        return Err(Failure::internal(strings::lobby_answer_unread(
            "its report is not an object",
        )));
    };
    let mut out = Vec::with_capacity(members.len());
    for (key, value) in members {
        let value = match key.as_str() {
            "depth" => enum_value(DEPTH, value)?,
            "diagnostics" => each(value, canonical_diagnostic)?,
            _ => value.clone(),
        };
        out.push((key.clone(), value));
    }
    Ok(Json::Object(out))
}

fn canonical_diagnostic(diagnostic: &Json) -> Result<Json, Failure> {
    let Json::Object(members) = diagnostic else {
        return Err(Failure::internal(strings::lobby_answer_unread(
            "a diagnostic is not an object",
        )));
    };
    let mut out = Vec::with_capacity(members.len());
    for (key, value) in members {
        let value = match key.as_str() {
            "severity" => enum_value(SEVERITY, value)?,
            "suggestions" => each(value, canonical_suggestion)?,
            _ => value.clone(),
        };
        out.push((key.clone(), value));
    }
    Ok(Json::Object(out))
}

fn canonical_suggestion(suggestion: &Json) -> Result<Json, Failure> {
    let Json::Object(members) = suggestion else {
        return Err(Failure::internal(strings::lobby_answer_unread(
            "a suggestion is not an object",
        )));
    };
    let mut out = Vec::with_capacity(members.len());
    for (key, value) in members {
        let value = match key.as_str() {
            "applicability" => enum_value(APPLICABILITY, value)?,
            _ => value.clone(),
        };
        out.push((key.clone(), value));
    }
    Ok(Json::Object(out))
}

fn each(value: &Json, one: fn(&Json) -> Result<Json, Failure>) -> Result<Json, Failure> {
    let Json::Array(items) = value else {
        return Err(Failure::internal(strings::lobby_answer_unread(
            "a list in its report is not an array",
        )));
    };
    items
        .iter()
        .map(one)
        .collect::<Result<Vec<Json>, Failure>>()
        .map(Json::Array)
}

fn enum_value(full_name: &str, value: &Json) -> Result<Json, Failure> {
    let Json::String(wire) = value else {
        return Err(Failure::internal(strings::lobby_answer_unread(&format!(
            "a `{full_name}` is not a string"
        ))));
    };
    pharmakos_proto::scope::from_wire_name(full_name, wire)
        .map(Json::String)
        .ok_or_else(|| {
            Failure::internal(strings::lobby_answer_unread(&format!(
                "`{}` is not a `{full_name}`",
                pharmakos_proto::json::grammar::quoted(wire)
            )))
        })
}

fn gateway(error: pharmakos_gateway::Error) -> Failure {
    Failure::internal(strings::lobby_match_refused(
        &error.into_said().into_string(),
    ))
}

#[cfg(test)]
mod tests {
    use super::{canonical_report, probation, report_of};
    use pharmakos_proto::json::Json;

    #[test]
    fn the_lobby_s_line_is_one_the_gateway_reads() {
        let config = probation().expect("the lobby's line");
        assert_eq!(config.seed, 20);
        assert_eq!(config.seats, 2);
        assert_eq!(config.human_seat, Some(0));
        assert_eq!(config.preset.name(), "probation");
    }

    #[test]
    fn a_wire_enum_the_schema_does_not_name_is_refused() {
        let report = pharmakos_proto::json::read(
            r#"{"qualifies": true, "depth": "deep", "diagnostics": []}"#,
        )
        .expect("json");
        let refused = canonical_report(&report).expect_err("refused");
        assert!(refused.message.contains("deep"), "{}", refused.message);
        let answer = Json::Object(vec![(String::from("result"), Json::Object(vec![]))]);
        assert!(report_of(&answer).is_err(), "an answer with no report");
    }
}
